/// `Find`: the entry of a NIF name.
#[must_use]
pub fn find(nif_name: &str) -> Option<&'static Entry> {
    HUMAN.iter().find(|e| e.nif_name == nif_name)
}

/// `Categories`: the distinct categories in table order, for the group pickers.
#[must_use]
pub fn categories() -> Vec<&'static str> {
    let mut out: Vec<&str> = Vec::new();
    for entry in HUMAN {
        if out.last() != Some(&entry.category) {
            out.push(entry.category);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::{CATEGORY_ORDER, HUMAN, categories, find};

    #[test]
    fn the_table_is_grouped_in_category_order_with_unique_names() {
        assert_eq!(HUMAN.len(), 390);
        assert_eq!(categories(), CATEGORY_ORDER);
        let mut names: Vec<&str> = HUMAN.iter().map(|e| e.nif_name).collect();
        names.sort_unstable();
        names.dedup();
        assert_eq!(names.len(), HUMAN.len());
        assert_eq!(find("NPC Head [Head]").map(|e| (e.display_name, e.category)), Some(("Head", "Main")));
        assert_eq!(find("PA Tongue").map(|e| e.category), Some("Niopa"));
        assert!(find("NPC Nonexistent").is_none());
    }
}
