//! Rust source of the layout crate from the loaded ledgers.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

use sha2::{Digest, Sha256};

use crate::inputs::{Field, Inputs, Symbol};

#[derive(Default)]
pub struct Stats {
    pub exact_classes: usize,
    pub partial_classes: usize,
    pub fields: usize,
    pub size_asserts: usize,
    pub offset_asserts: usize,
    pub vtables: usize,
    pub slots: usize,
    pub functions: usize,
    pub globals: usize,
    pub enum_values: usize,
}

const HEADER: &str = "//! Generated by `cargo xtask gen` from the SkyrimRE-1.7.104 ledgers; do not edit.\n\
#![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, unused_imports, clippy::all, clippy::pedantic)]\n\n";

const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate", "do", "dyn", "else", "enum",
    "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut",
    "override", "priv", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "try", "type",
    "typeof", "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

/// A Rust identifier for a ledger name: `::` becomes `__`, every other run of non-identifier
/// characters `_`, and names over 120 characters end in a hash of the original.
fn ident(name: &str) -> String {
    let mut out = String::new();
    for (i, token) in name.split("::").enumerate() {
        if i > 0 {
            out.push_str("__");
        }
        let mut pending = false;
        for c in token.chars() {
            if c.is_ascii_alphanumeric() || c == '_' {
                if pending {
                    out.push('_');
                    pending = false;
                }
                out.push(c);
            } else {
                pending = true;
            }
        }
    }
    if out.is_empty() || out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    if out.len() > 120 {
        let hash = Sha256::digest(name.as_bytes());
        out.truncate(96);
        write!(out, "_{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}", hash[0], hash[1], hash[2], hash[3], hash[4], hash[5]).unwrap();
    }
    out
}

/// Makes identifiers unique within one namespace; later duplicates get `_2`, `_3`, ...
fn unique(idents: &mut [String]) {
    let mut seen: HashMap<String, usize> = HashMap::new();
    for id in idents.iter_mut() {
        let n = seen.entry(id.clone()).or_insert(0);
        *n += 1;
        if *n > 1 {
            let mut k = *n;
            while seen.contains_key(&format!("{id}_{k}")) {
                k += 1;
            }
            *id = format!("{id}_{k}");
            seen.insert(id.clone(), 1);
        }
    }
}

fn doc(text: &str) -> String {
    text.replace(['\r', '\n'], " ")
}

enum Size {
    Exact { size: u64, conf: Option<String>, evidence: String },
    Partial { lower: u64, upper: Option<u64>, evidence: String },
}

#[derive(Clone)]
enum Ty {
    U8,
    U16,
    U32,
    U64,
    F32,
    F64,
    Bytes(u64),
    PtrVoid,
    Ptr(String),
    Embed(String),
    Vtable(String),
}

struct Class<'a> {
    name: &'a str,
    ident: String,
    size: Size,
    fields: Vec<(&'a Field, String, Ty)>,
    primary_base: Option<&'a str>,
    bases: Vec<(&'a str, i64, bool)>,
    packed: bool,
    align: u64,
}

impl Class<'_> {
    fn partial(&self) -> bool {
        matches!(self.size, Size::Partial { .. })
    }

    fn extent(&self) -> u64 {
        match self.size {
            Size::Exact { size, .. } | Size::Partial { lower: size, .. } => size,
        }
    }
}

fn vtable_ident(class_ident: &str, offset: u64) -> String {
    if offset == 0 { format!("{class_ident}_vtable") } else { format!("{class_ident}_vtable_{offset:X}") }
}

fn resolve(f: &Field, classes: &BTreeMap<&str, Class>, class_idents: &HashMap<&str, String>) -> Ty {
    let prim = match (f.ty.as_str(), f.size) {
        ("undefined1", 1) => Some(Ty::U8),
        ("undefined2", 2) => Some(Ty::U16),
        ("undefined4", 4) => Some(Ty::U32),
        ("undefined8", 8) => Some(Ty::U64),
        ("float", 4) => Some(Ty::F32),
        ("double", 8) => Some(Ty::F64),
        ("pointer", 8) => Some(Ty::PtrVoid),
        _ => None,
    };
    if let Some(p) = prim {
        return p;
    }
    if let Some(target) = f.ty.strip_prefix("ptr:") {
        if f.size == 8 {
            return if classes.contains_key(target) { Ty::Ptr(target.to_owned()) } else { Ty::PtrVoid };
        }
    } else if let Some(target) = f.ty.strip_prefix("class:") {
        if let Some(c) = classes.get(target)
            && matches!(c.size, Size::Exact { size, .. } if size == f.size)
        {
            return Ty::Embed(target.to_owned());
        }
    } else if let Some(body) = f.ty.strip_prefix("vtbl:")
        && f.size == 8
    {
        let (class, off) = body.rsplit_once(':').expect("vtbl type has an offset");
        let off = u64::from_str_radix(off, 16).expect("vtbl offset is hex");
        return Ty::Vtable(vtable_ident(&class_idents[class], off));
    }
    Ty::Bytes(f.size)
}

fn ty_align(ty: &Ty, classes: &BTreeMap<&str, Class>) -> u64 {
    match ty {
        Ty::U8 | Ty::Bytes(_) => 1,
        Ty::U16 => 2,
        Ty::U32 | Ty::F32 => 4,
        Ty::U64 | Ty::F64 | Ty::PtrVoid | Ty::Ptr(_) | Ty::Vtable(_) => 8,
        Ty::Embed(c) => classes[c.as_str()].align,
    }
}

fn ty_str(ty: &Ty, in_partial: bool, classes: &BTreeMap<&str, Class>) -> String {
    let path = |c: &str| {
        let class = &classes[c];
        match (in_partial, class.partial()) {
            (true, true) | (false, false) => class.ident.clone(),
            (true, false) => format!("super::{}", class.ident),
            (false, true) => format!("partial::{}", class.ident),
        }
    };
    match ty {
        Ty::U8 => "u8".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::F32 => "f32".into(),
        Ty::F64 => "f64".into(),
        Ty::Bytes(n) => format!("[u8; {n}]"),
        Ty::PtrVoid => "*mut c_void".into(),
        Ty::Ptr(c) => format!("*mut {}", path(c)),
        Ty::Embed(c) => path(c),
        Ty::Vtable(v) => format!("*const vtables::{v}"),
    }
}

fn build_classes(inp: &Inputs) -> BTreeMap<&str, Class<'_>> {
    let rtti: HashMap<&str, _> = inp.rtti.classes.iter().map(|c| (c.name.as_str(), c)).collect();
    let mut classes: BTreeMap<&str, Class> = BTreeMap::new();
    for (name, l) in &inp.layouts {
        let end = l.fields.iter().map(|f| f.off + f.size).max().unwrap_or(0);
        let size = match l.size_kind.as_str() {
            "exact" => Size::Exact { size: l.size.unwrap(), conf: l.size_conf.clone(), evidence: l.size_evidence.clone() },
            "conflict" if end <= l.size.unwrap() => Size::Exact {
                size: l.size.unwrap(),
                conf: l.size_conf.clone(),
                evidence: format!("conflict, allocation size kept: {}", l.size_evidence),
            },
            "conflict" => Size::Partial {
                lower: end,
                upper: None,
                evidence: format!("conflict, field extent kept over the allocation size: {}", l.size_evidence),
            },
            "bounded" => Size::Partial { lower: l.size_lower, upper: l.size_upper, evidence: l.size_evidence.clone() },
            "lower" => Size::Partial { lower: l.size_lower, upper: None, evidence: l.size_evidence.clone() },
            other => panic!("{name}: unknown size_kind {other}"),
        };
        let bases = rtti[name.as_str()]
            .bases
            .iter()
            .skip(1)
            .map(|b| (b.name.as_str(), b.mdisp, b.pdisp != -1))
            .collect();
        let class = Class {
            name,
            ident: String::new(),
            size,
            fields: l.fields.iter().map(|f| (f, String::new(), Ty::Bytes(f.size))).collect(),
            primary_base: l.primary_base.as_deref(),
            bases,
            packed: false,
            align: 1,
        };
        classes.insert(name, class);
    }
    for (name, s) in &inp.structs.structs {
        assert!(!classes.contains_key(name.as_str()), "{name} is both an RTTI class and a class_structs entry");
        let size = if s.lower_bound {
            Size::Partial { lower: s.size, upper: None, evidence: s.description.clone() }
        } else {
            Size::Exact { size: s.size, conf: None, evidence: s.description.clone() }
        };
        let class = Class {
            name,
            ident: String::new(),
            size,
            fields: s.fields.iter().map(|f| (f, String::new(), Ty::Bytes(f.size))).collect(),
            primary_base: None,
            bases: Vec::new(),
            packed: false,
            align: 1,
        };
        classes.insert(name, class);
    }

    let mut idents: Vec<String> = classes.keys().map(|n| ident(n)).collect();
    unique(&mut idents);
    for (c, id) in classes.values_mut().zip(idents) {
        c.ident = id;
    }
    let class_idents: HashMap<&str, String> = classes.values().map(|c| (c.name, c.ident.clone())).collect();

    let names: Vec<&str> = classes.keys().copied().collect();
    for name in &names {
        let fields: Vec<_> = classes[name]
            .fields
            .iter()
            .map(|(f, _, _)| {
                let ty = resolve(f, &classes, &class_idents);
                (*f, ident(&f.name), ty)
            })
            .collect();
        let mut field_idents: Vec<String> = fields.iter().map(|(_, id, _)| id.clone()).collect();
        unique(&mut field_idents);
        let class = classes.get_mut(name).unwrap();
        class.fields = fields.into_iter().zip(field_idents).map(|((f, _, ty), id)| (f, id, ty)).collect();
    }

    for name in &names {
        layout_of(name, &mut classes);
    }
    classes
}

/// Alignment and packing of a class, with embedded classes resolved first.
fn layout_of(name: &str, classes: &mut BTreeMap<&str, Class>) -> u64 {
    if classes[name].align > 1 || classes[name].packed {
        return classes[name].align;
    }
    let embedded: Vec<String> = classes[name]
        .fields
        .iter()
        .filter_map(|(_, _, ty)| if let Ty::Embed(c) = ty { Some(c.clone()) } else { None })
        .collect();
    for e in embedded {
        layout_of(&e, classes);
    }
    let class = &classes[name];
    let mut align = 1;
    let mut packed = false;
    for (f, _, ty) in &class.fields {
        let a = ty_align(ty, classes);
        align = align.max(a);
        packed |= f.off % a != 0;
    }
    if let Size::Exact { size, .. } = class.size {
        packed |= size % align != 0;
    }
    let class = classes.get_mut(name).unwrap();
    class.packed = packed;
    class.align = if packed { 1 } else { align };
    class.align
}

fn write_class(out: &mut String, c: &Class, in_partial: bool, classes: &BTreeMap<&str, Class>, stats: &mut Stats) {
    let indent = if in_partial { "    " } else { "" };
    let mut head = match &c.size {
        Size::Exact { size, conf, evidence: _ } => {
            format!("`{}`: size {size:#X} (exact{})", c.name, conf.as_deref().map(|s| format!(", {s}")).unwrap_or_default())
        }
        Size::Partial { lower, upper, .. } => format!(
            "`{}`: size >= {lower:#X} (lower bound{}); partial, the struct stops at the lower bound",
            c.name,
            upper.map(|u| format!(", upper bound {u:#X}")).unwrap_or_default()
        ),
    };
    if let Some(b) = c.primary_base {
        write!(head, "; primary base `{b}`").unwrap();
    }
    let evidence = match &c.size {
        Size::Exact { evidence, .. } | Size::Partial { evidence, .. } => evidence,
    };
    writeln!(out, "{indent}/// {}.", doc(&head)).unwrap();
    writeln!(out, "{indent}/// Evidence: {}.", doc(evidence)).unwrap();
    if !c.bases.is_empty() {
        let bases: Vec<String> = c
            .bases
            .iter()
            .map(|(n, off, virt)| format!("`{n}`@{off:#X}{}", if *virt { " (virtual)" } else { "" }))
            .collect();
        writeln!(out, "{indent}/// Bases: {}.", doc(&bases.join(", "))).unwrap();
    }
    if c.packed {
        writeln!(out, "{indent}/// Packed: a field lies below its natural alignment.").unwrap();
    }
    writeln!(out, "{indent}#[repr(C{})]", if c.packed { ", packed" } else { "" }).unwrap();
    writeln!(out, "{indent}pub struct {} {{", c.ident).unwrap();
    let mut pos = 0;
    for (f, id, ty) in &c.fields {
        assert!(f.off >= pos, "{}: field {} at {:#X} overlaps the previous field", c.name, f.name, f.off);
        if f.off > pos {
            writeln!(out, "{indent}    pub unknown_{pos:X}: [u8; {}],", f.off - pos).unwrap();
        }
        let src = if f.src.is_empty() { String::new() } else { format!(", {}", doc(&f.src)) };
        writeln!(out, "{indent}    /// +{:#X} `{}`{src}", f.off, doc(&f.ty)).unwrap();
        writeln!(out, "{indent}    pub {id}: {},", ty_str(ty, in_partial, classes)).unwrap();
        pos = f.off + f.size;
        stats.fields += 1;
    }
    let extent = c.extent();
    assert!(pos <= extent, "{}: fields extend past {extent:#X}", c.name);
    if pos < extent {
        writeln!(out, "{indent}    pub unknown_{pos:X}: [u8; {}],", extent - pos).unwrap();
    }
    writeln!(out, "{indent}}}").unwrap();
    if let Size::Exact { size, .. } = c.size {
        writeln!(out, "{indent}const _: () = assert!(size_of::<{}>() == {size:#X});", c.ident).unwrap();
        stats.size_asserts += 1;
        stats.exact_classes += 1;
    } else {
        stats.partial_classes += 1;
    }
    for (f, id, _) in &c.fields {
        writeln!(out, "{indent}const _: () = assert!(core::mem::offset_of!({}, {id}) == {:#X});", c.ident, f.off).unwrap();
        stats.offset_asserts += 1;
    }
    out.push('\n');
}

fn classes_rs(classes: &BTreeMap<&str, Class>, stats: &mut Stats) -> String {
    let mut out = String::from(HEADER);
    out.push_str("use core::ffi::c_void;\n\nuse super::vtables;\n\n");
    for c in classes.values().filter(|c| !c.partial()) {
        write_class(&mut out, c, false, classes, stats);
    }
    out.push_str("/// Classes whose size is only bounded below; each struct stops at the lower bound.\npub mod partial {\n");
    out.push_str("    use core::ffi::c_void;\n\n    use super::vtables;\n\n");
    for c in classes.values().filter(|c| c.partial()) {
        write_class(&mut out, c, true, classes, stats);
    }
    out.push_str("}\n");
    out
}

fn symbol_doc(s: &Symbol) -> String {
    let mut d = format!("`{}` at {:#x} ({}, {})", s.name, s.rva, s.evidence, s.confidence);
    if !s.signature.is_empty() {
        let tier = if s.sig_confidence.is_empty() { "untiered" } else { &s.sig_confidence };
        write!(d, "; signature ({tier}): `{}`", s.signature).unwrap();
    }
    doc(&d)
}

fn vtables_rs(inp: &Inputs, classes: &BTreeMap<&str, Class>, stats: &mut Stats) -> String {
    let by_rva: HashMap<u64, &Symbol> = inp.symbols.iter().map(|s| (s.rva, s)).collect();
    let mut out = String::from(HEADER);
    out.push_str("use core::ffi::c_void;\n\nuse crate::Vtable;\n\n");
    let mut all = Vec::new();
    let mut rtti: Vec<_> = inp.rtti.classes.iter().collect();
    rtti.sort_by(|a, b| a.name.cmp(&b.name));
    for class in rtti {
        let class_ident = &classes[class.name.as_str()].ident;
        let mut cols: Vec<_> = class.cols.iter().collect();
        cols.sort_by_key(|c| c.offset);
        for col in cols {
            let sym = by_rva.get(&col.vtable).unwrap_or_else(|| panic!("{}: vtable at {:#x} has no symbol", class.name, col.vtable));
            let id = sym.id.unwrap_or_else(|| panic!("{}: vtable symbol {} has no id", class.name, sym.name));
            let vt = vtable_ident(class_ident, col.offset);
            writeln!(out, "/// `{}` at {:#x}, id {id} ({}, {}); {} slots.", doc(&sym.name), sym.rva, sym.evidence, sym.confidence, col.slots.len()).unwrap();
            writeln!(out, "#[repr(C)]\npub struct {vt} {{").unwrap();
            for (i, target) in col.slots.iter().enumerate() {
                match by_rva.get(target) {
                    Some(t) => writeln!(out, "    /// {}", symbol_doc(t)).unwrap(),
                    None => writeln!(out, "    /// no symbol at {target:#x}").unwrap(),
                }
                writeln!(out, "    pub slot_{i}: *const c_void,").unwrap();
                stats.slots += 1;
            }
            writeln!(out, "}}\nimpl {vt} {{\n    pub const ID: u64 = {id};\n}}\n").unwrap();
            all.push((sym.rva, class.name.as_str(), col.offset, id));
            stats.vtables += 1;
        }
    }
    all.sort_unstable();
    out.push_str("/// Every vtable the RTTI records, sorted by rva.\npub static ALL: &[Vtable] = &[\n");
    for (rva, class, offset, id) in all {
        writeln!(out, "    Vtable {{ class: {class:?}, offset: {offset:#X}, id: {id}, rva: {rva:#x} }},").unwrap();
    }
    out.push_str("];\n\n/// The vtable at a module-relative address.\n#[must_use]\npub fn find(rva: u32) -> Option<&'static Vtable> {\n    ALL.binary_search_by_key(&rva, |v| v.rva).ok().map(|i| &ALL[i])\n}\n");
    out
}

fn is_funclet(s: &Symbol) -> bool {
    s.evidence == "eh_table" || s.name.contains("__unwind_") || s.name.contains("__catch_")
}

fn is_placeholder(name: &str) -> bool {
    name.strip_prefix("ID_").is_some_and(|rest| !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit()))
}

fn consts_rs(symbols: Vec<&Symbol>, docs: &dyn Fn(&Symbol) -> String, count: &mut usize) -> String {
    let mut symbols = symbols;
    symbols.sort_by(|a, b| a.name.cmp(&b.name).then(a.id.cmp(&b.id)));
    let mut idents: Vec<String> = symbols.iter().map(|s| ident(&s.name)).collect();
    unique(&mut idents);
    let mut out = String::from(HEADER);
    for (s, id) in symbols.iter().zip(idents) {
        writeln!(out, "/// {}\npub const {id}: u64 = {};", docs(s), s.id.unwrap()).unwrap();
        *count += 1;
    }
    out
}

fn fns_rs(inp: &Inputs, stats: &mut Stats) -> String {
    let selected = inp
        .symbols
        .iter()
        .filter(|s| {
            s.kind == "function"
                && s.id.is_some()
                && matches!(s.confidence.as_str(), "high" | "medium")
                && !is_placeholder(&s.name)
                && !is_funclet(s)
        })
        .collect();
    consts_rs(selected, &symbol_doc, &mut stats.functions)
}

fn globals_rs(inp: &Inputs, stats: &mut Stats) -> String {
    let labels: HashMap<u64, _> = inp.structs.labels.iter().filter(|l| l.pointer).map(|l| (l.rva, l)).collect();
    let selected = inp.symbols.iter().filter(|s| s.kind == "global" && s.id.is_some()).collect();
    let docs = |s: &Symbol| match labels.get(&s.rva) {
        Some(l) => format!("{}; pointer to `{}`: {}", symbol_doc(s), l.cls, doc(&l.detail)),
        None => symbol_doc(s),
    };
    consts_rs(selected, &docs, &mut stats.globals)
}

fn enums_rs(inp: &Inputs, stats: &mut Stats) -> String {
    let source = inp.symbols.iter().find(|s| s.name == "g_FormTypeSignatures");
    let mut out = String::from(HEADER);
    let mut forms: Vec<_> = inp.formtypes.iter().collect();
    forms.sort_by_key(|f| f.id);
    let mut idents: Vec<String> = forms.iter().map(|f| ident(&f.sig)).collect();
    unique(&mut idents);
    out.push_str("/// Record signatures indexed by form type");
    if let Some(s) = source {
        write!(out, ", from {}", symbol_doc(s)).unwrap();
    }
    out.push_str(".\n/// The `u8` width is the generator's choice for a table of this length; the ledger does not record the field width.\n");
    out.push_str("#[repr(u8)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum FormType {\n");
    for (f, id) in forms.iter().zip(&idents) {
        match &f.cls {
            Some(c) => writeln!(out, "    /// `{}`, class `{c}`", f.sig).unwrap(),
            None => writeln!(out, "    /// `{}`", f.sig).unwrap(),
        }
        writeln!(out, "    {id} = {},", f.id).unwrap();
        stats.enum_values += 1;
    }
    out.push_str("}\n\nimpl FormType {\n    #[must_use]\n    pub const fn from_u8(value: u8) -> Option<Self> {\n        match value {\n");
    for (f, id) in forms.iter().zip(&idents) {
        writeln!(out, "            {} => Some(Self::{id}),", f.id).unwrap();
    }
    out.push_str("            _ => None,\n        }\n    }\n\n    #[must_use]\n    pub const fn signature(self) -> &'static str {\n        match self {\n");
    for (f, id) in forms.iter().zip(&idents) {
        writeln!(out, "            Self::{id} => {:?},", f.sig).unwrap();
    }
    out.push_str("        }\n    }\n}\n");
    out
}

fn mod_rs(commit: &str) -> String {
    format!(
        "//! SkyrimSE.exe 1.7.104 as the SkyrimRE-1.7.104 ledgers describe it at commit {commit}.\n\
         //! Generated by `cargo xtask gen`; do not edit.\n\n\
         #[rustfmt::skip]\npub mod classes;\n#[rustfmt::skip]\npub mod enums;\n#[rustfmt::skip]\npub mod fns;\n\
         #[rustfmt::skip]\npub mod globals;\n#[rustfmt::skip]\npub mod vtables;\n\n\
         /// The runtime these definitions describe, as `[major, minor, build]`.\npub const VERSION: [u32; 3] = [1, 7, 104];\n"
    )
}

/// The generated module files keyed by file name, and what they contain.
pub fn all(inp: &Inputs, commit: &str) -> (BTreeMap<&'static str, String>, Stats) {
    let mut stats = Stats::default();
    let classes = build_classes(inp);
    let mut files = BTreeMap::new();
    files.insert("classes.rs", classes_rs(&classes, &mut stats));
    files.insert("vtables.rs", vtables_rs(inp, &classes, &mut stats));
    files.insert("fns.rs", fns_rs(inp, &mut stats));
    files.insert("globals.rs", globals_rs(inp, &mut stats));
    files.insert("enums.rs", enums_rs(inp, &mut stats));
    files.insert("mod.rs", mod_rs(commit));
    (files, stats)
}
