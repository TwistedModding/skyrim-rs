const KEYWORDS: &[&str] = &[
    "abstract", "as", "async", "await", "become", "box", "break", "const", "continue", "crate", "do", "dyn", "else", "enum",
    "extern", "false", "final", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "macro", "match", "mod", "move", "mut",
    "override", "priv", "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "try", "type",
    "typeof", "unsafe", "unsized", "use", "virtual", "where", "while", "yield",
];

/// A Rust identifier for a ledger name: `::` becomes `__`, every other run of non-identifier
/// characters `_`, and names over 120 characters end in a hash of the original.
fn ident(name: &str) -> String {
    let mut out = String::new();
    for (i, token) in name.split("::").enumerate() {
        if i > 0 {
            out.push_str("__");
        }
        let mut pending = false;
        for c in token.chars() {
            if c.is_ascii_alphanumeric() || c == '_' {
                if pending {
                    out.push('_');
                    pending = false;
                }
                out.push(c);
            } else {
                pending = true;
            }
        }
    }
    if out.is_empty() || out.as_bytes()[0].is_ascii_digit() {
        out.insert(0, '_');
    }
    if KEYWORDS.contains(&out.as_str()) {
        out.push('_');
    }
    if out.len() > 120 {
        let hash = Sha256::digest(name.as_bytes());
        out.truncate(96);
        write!(out, "_{:02x}{:02x}{:02x}{:02x}{:02x}{:02x}", hash[0], hash[1], hash[2], hash[3], hash[4], hash[5]).unwrap();
    }
    out
}

/// `PlayerKnows` becomes `PLAYER_KNOWS`.
fn screaming(name: &str) -> String {
    let chars: Vec<char> = ident(name).chars().collect();
    let mut out = String::new();
    for (i, &c) in chars.iter().enumerate() {
        if c.is_ascii_uppercase()
            && i > 0
            && chars[i - 1] != '_'
            && (chars[i - 1].is_ascii_lowercase()
                || chars[i - 1].is_ascii_digit()
                || chars.get(i + 1).is_some_and(char::is_ascii_lowercase))
        {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

/// Makes identifiers unique within one namespace; later duplicates get `_2`, `_3`, ...
fn unique(idents: &mut [String]) {
    let mut seen: HashMap<String, usize> = HashMap::new();
    for id in idents.iter_mut() {
        let n = seen.entry(id.clone()).or_insert(0);
        *n += 1;
        if *n > 1 {
            let mut k = *n;
            while seen.contains_key(&format!("{id}_{k}")) {
                k += 1;
            }
            *id = format!("{id}_{k}");
            seen.insert(id.clone(), 1);
        }
    }
}

fn doc(text: &str) -> String {
    text.replace(['\r', '\n'], " ")
}

enum Size {
    Exact { size: u64, conf: Option<String>, evidence: String },
    Partial { lower: u64, upper: Option<u64>, evidence: String },
}

#[derive(Clone)]
enum Ty {
    U8,
    U16,
    U32,
    U64,
    F32,
    F64,
    Bytes(u64),
    PtrVoid,
    Ptr(String),
    Embed(String),
    Vtable(String),
}

struct FieldOut<'a> {
    f: &'a Field,
    ident: String,
    ty: Ty,
    meaning: String,
}

struct Class<'a> {
    name: &'a str,
    ident: String,
    size: Size,
    fields: Vec<FieldOut<'a>>,
    primary_base: Option<&'a str>,
    bases: Vec<(&'a str, i64, bool)>,
    packed: bool,
    align: u64,
    meaning: String,
}

impl Class<'_> {
    fn partial(&self) -> bool {
        matches!(self.size, Size::Partial { .. })
    }

    fn extent(&self) -> u64 {
        match self.size {
            Size::Exact { size, .. } | Size::Partial { lower: size, .. } => size,
        }
    }

    /// The struct's path from a sibling module of `classes`.
    fn path(&self) -> String {
        if self.partial() { format!("classes::partial::{}", self.ident) } else { format!("classes::{}", self.ident) }
    }
}

fn vtable_ident(class_ident: &str, offset: u64) -> String {
    if offset == 0 { format!("{class_ident}_vtable") } else { format!("{class_ident}_vtable_{offset:X}") }
}

fn resolve(f: &Field, classes: &BTreeMap<&str, Class>, class_idents: &HashMap<&str, String>) -> Ty {
    let prim = match (f.ty.as_str(), f.size) {
        ("undefined1", 1) => Some(Ty::U8),
        ("undefined2", 2) => Some(Ty::U16),
        ("undefined4", 4) => Some(Ty::U32),
        ("undefined8", 8) => Some(Ty::U64),
        ("float", 4) => Some(Ty::F32),
        ("double", 8) => Some(Ty::F64),
        ("pointer", 8) => Some(Ty::PtrVoid),
        _ => None,
    };
    if let Some(p) = prim {
        return p;
    }
    if let Some(target) = f.ty.strip_prefix("ptr:") {
        if f.size == 8 {
            return if classes.contains_key(target) { Ty::Ptr(target.to_owned()) } else { Ty::PtrVoid };
        }
    } else if let Some(target) = f.ty.strip_prefix("class:") {
        if let Some(c) = classes.get(target)
            && matches!(c.size, Size::Exact { size, .. } if size == f.size)
        {
            return Ty::Embed(target.to_owned());
        }
    } else if let Some(body) = f.ty.strip_prefix("vtbl:")
        && f.size == 8
    {
        let (class, off) = body.rsplit_once(':').expect("vtbl type has an offset");
        let off = u64::from_str_radix(off, 16).expect("vtbl offset is hex");
        return Ty::Vtable(vtable_ident(&class_idents[class], off));
    }
    Ty::Bytes(f.size)
}

fn ty_align(ty: &Ty, classes: &BTreeMap<&str, Class>) -> u64 {
    match ty {
        Ty::U8 | Ty::Bytes(_) => 1,
        Ty::U16 => 2,
        Ty::U32 | Ty::F32 => 4,
        Ty::U64 | Ty::F64 | Ty::PtrVoid | Ty::Ptr(_) | Ty::Vtable(_) => 8,
        Ty::Embed(c) => classes[c.as_str()].align,
    }
}

fn ty_str(ty: &Ty, in_partial: bool, classes: &BTreeMap<&str, Class>) -> String {
    let path = |c: &str| {
        let class = &classes[c];
        match (in_partial, class.partial()) {
            (true, true) | (false, false) => class.ident.clone(),
            (true, false) => format!("super::{}", class.ident),
            (false, true) => format!("partial::{}", class.ident),
        }
    };
    match ty {
        Ty::U8 => "u8".into(),
        Ty::U16 => "u16".into(),
        Ty::U32 => "u32".into(),
        Ty::U64 => "u64".into(),
        Ty::F32 => "f32".into(),
        Ty::F64 => "f64".into(),
        Ty::Bytes(n) => format!("[u8; {n}]"),
        Ty::PtrVoid => "*mut c_void".into(),
        Ty::Ptr(c) => format!("*mut {}", path(c)),
        Ty::Embed(c) => path(c),
        Ty::Vtable(v) => format!("*const vtables::{v}"),
    }
}

/// The semantic classes of every pass keyed by class name, with the pass they come from.
fn sem_classes(inp: &Inputs) -> HashMap<&str, (&SemClass, &str)> {
    let mut out = HashMap::new();
    for pass in &inp.semantic {
        for c in &pass.classes {
            assert!(out.insert(c.name.as_str(), (c, pass.subsystem.as_str())).is_none(), "{} is in two semantic passes", c.name);
        }
    }
    out
}

fn build_classes(inp: &Inputs) -> BTreeMap<&str, Class<'_>> {
    let rtti: HashMap<&str, _> = inp.rtti.classes.iter().map(|c| (c.name.as_str(), c)).collect();
    let mut classes: BTreeMap<&str, Class> = BTreeMap::new();
    for (name, l) in &inp.layouts {
        let end = l.fields.iter().map(|f| f.off + f.size).max().unwrap_or(0);
        let size = match l.size_kind.as_str() {
            "exact" => Size::Exact { size: l.size.unwrap(), conf: l.size_conf.clone(), evidence: l.size_evidence.clone() },
            "conflict" if end <= l.size.unwrap() => Size::Exact {
                size: l.size.unwrap(),
                conf: l.size_conf.clone(),
                evidence: format!("conflict, allocation size kept: {}", l.size_evidence),
            },
            "conflict" => Size::Partial {
                lower: end,
                upper: None,
                evidence: format!("conflict, field extent kept over the allocation size: {}", l.size_evidence),
            },
            "bounded" => Size::Partial { lower: l.size_lower, upper: l.size_upper, evidence: l.size_evidence.clone() },
            "lower" => Size::Partial { lower: l.size_lower, upper: None, evidence: l.size_evidence.clone() },
            other => panic!("{name}: unknown size_kind {other}"),
        };
        let bases = rtti[name.as_str()]
            .bases
            .iter()
            .skip(1)
            .map(|b| (b.name.as_str(), b.mdisp, b.pdisp != -1))
            .collect();
        let class = Class {
            name,
            ident: String::new(),
            size,
            fields: l.fields.iter().map(|f| FieldOut { f, ident: String::new(), ty: Ty::Bytes(f.size), meaning: String::new() }).collect(),
            primary_base: l.primary_base.as_deref(),
            bases,
            packed: false,
            align: 1,
            meaning: String::new(),
        };
        classes.insert(name, class);
    }
    for (name, s) in &inp.structs.structs {
        assert!(!classes.contains_key(name.as_str()), "{name} is both an RTTI class and a class_structs entry");
        let size = if s.lower_bound {
            Size::Partial { lower: s.size, upper: None, evidence: s.description.clone() }
        } else {
            Size::Exact { size: s.size, conf: None, evidence: s.description.clone() }
        };
        let class = Class {
            name,
            ident: String::new(),
            size,
            fields: s.fields.iter().map(|f| FieldOut { f, ident: String::new(), ty: Ty::Bytes(f.size), meaning: String::new() }).collect(),
            primary_base: None,
            bases: Vec::new(),
            packed: false,
            align: 1,
            meaning: String::new(),
        };
        classes.insert(name, class);
    }

    let mut idents: Vec<String> = classes.keys().map(|n| ident(n)).collect();
    unique(&mut idents);
    for (c, id) in classes.values_mut().zip(idents) {
        c.ident = id;
    }
    let class_idents: HashMap<&str, String> = classes.values().map(|c| (c.name, c.ident.clone())).collect();

    let names: Vec<&str> = classes.keys().copied().collect();
    for name in &names {
        let resolved: Vec<Ty> = classes[name].fields.iter().map(|fo| resolve(fo.f, &classes, &class_idents)).collect();
        let class = classes.get_mut(name).unwrap();
        let mut field_idents: Vec<String> = class.fields.iter().map(|fo| ident(&fo.f.name)).collect();
        unique(&mut field_idents);
        for ((fo, ty), id) in class.fields.iter_mut().zip(resolved).zip(field_idents) {
            fo.ty = ty;
            fo.ident = id;
        }
    }

    for name in &names {
        layout_of(name, &mut classes);
    }

    let sem = sem_classes(inp);
    for name in &names {
        let class = classes.get_mut(name).unwrap();
        if let Some((s, pass)) = sem.get(name) {
            class.meaning = format!("{} ({}, {pass} pass)", doc(&s.meaning), s.confidence);
        }
        let mut subobjects = vec![(*name, 0i64)];
        subobjects.extend(class.bases.iter().map(|(b, disp, _)| (*b, *disp)));
        for (base, disp) in subobjects {
            let Some((s, _)) = sem.get(base) else { continue };
            for sf in &s.fields {
                let off = u64::try_from(disp).unwrap() + sf.offset;
                if let Some(fo) = class.fields.iter_mut().find(|fo| fo.f.off == off && fo.f.name == sf.name) {
                    fo.meaning = format!("{} ({})", doc(&sf.meaning), sf.confidence);
                }
            }
        }
    }
    classes
}

/// Alignment and packing of a class, with embedded classes resolved first.
fn layout_of(name: &str, classes: &mut BTreeMap<&str, Class>) -> u64 {
    if classes[name].align > 1 || classes[name].packed {
        return classes[name].align;
    }
    let embedded: Vec<String> = classes[name]
        .fields
        .iter()
        .filter_map(|fo| if let Ty::Embed(c) = &fo.ty { Some(c.clone()) } else { None })
        .collect();
    for e in embedded {
        layout_of(&e, classes);
    }
    let class = &classes[name];
    let mut align = 1;
    let mut packed = false;
    for fo in &class.fields {
        let a = ty_align(&fo.ty, classes);
        align = align.max(a);
        packed |= fo.f.off % a != 0;
    }
    if let Size::Exact { size, .. } = class.size {
        packed |= size % align != 0;
    }
    let class = classes.get_mut(name).unwrap();
    class.packed = packed;
    class.align = if packed { 1 } else { align };
    class.align
}

fn write_class(out: &mut String, c: &Class, in_partial: bool, classes: &BTreeMap<&str, Class>, stats: &mut Stats) {
    let indent = if in_partial { "    " } else { "" };
    let mut head = match &c.size {
        Size::Exact { size, conf, evidence: _ } => {
            format!("`{}`: size {size:#X} (exact{})", c.name, conf.as_deref().map(|s| format!(", {s}")).unwrap_or_default())
        }
        Size::Partial { lower, upper, .. } => format!(
            "`{}`: size >= {lower:#X} (lower bound{}); partial, the struct stops at the lower bound",
            c.name,
            upper.map(|u| format!(", upper bound {u:#X}")).unwrap_or_default()
        ),
    };
    if let Some(b) = c.primary_base {
        write!(head, "; primary base `{b}`").unwrap();
    }
    let evidence = match &c.size {
        Size::Exact { evidence, .. } | Size::Partial { evidence, .. } => evidence,
    };
    writeln!(out, "{indent}/// {}.", doc(&head)).unwrap();
    if !c.meaning.is_empty() {
        writeln!(out, "{indent}/// Meaning: {}.", c.meaning).unwrap();
    }
    writeln!(out, "{indent}/// Evidence: {}.", doc(evidence)).unwrap();
    if !c.bases.is_empty() {
        let bases: Vec<String> = c
            .bases
            .iter()
            .map(|(n, off, virt)| format!("`{n}`@{off:#X}{}", if *virt { " (virtual)" } else { "" }))
            .collect();
        writeln!(out, "{indent}/// Bases: {}.", doc(&bases.join(", "))).unwrap();
    }
    if c.packed {
        writeln!(out, "{indent}/// Packed: a field lies below its natural alignment.").unwrap();
    }
    writeln!(out, "{indent}#[repr(C{})]", if c.packed { ", packed" } else { "" }).unwrap();
    writeln!(out, "{indent}pub struct {} {{", c.ident).unwrap();
    let mut pos = 0;
    for fo in &c.fields {
        let f = fo.f;
        assert!(f.off >= pos, "{}: field {} at {:#X} overlaps the previous field", c.name, f.name, f.off);
        if f.off > pos {
            writeln!(out, "{indent}    pub unknown_{pos:X}: [u8; {}],", f.off - pos).unwrap();
        }
        let src = if f.src.is_empty() { String::new() } else { format!(", {}", doc(&f.src)) };
        let meaning = if fo.meaning.is_empty() {
            String::new()
        } else {
            stats.field_meanings += 1;
            format!("; {}", fo.meaning)
        };
        writeln!(out, "{indent}    /// +{:#X} `{}`{src}{meaning}", f.off, doc(&f.ty)).unwrap();
        writeln!(out, "{indent}    pub {}: {},", fo.ident, ty_str(&fo.ty, in_partial, classes)).unwrap();
        pos = f.off + f.size;
        stats.fields += 1;
    }
    let extent = c.extent();
    assert!(pos <= extent, "{}: fields extend past {extent:#X}", c.name);
    if pos < extent {
        writeln!(out, "{indent}    pub unknown_{pos:X}: [u8; {}],", extent - pos).unwrap();
    }
    writeln!(out, "{indent}}}").unwrap();
    if let Size::Exact { size, .. } = c.size {
        writeln!(out, "{indent}const _: () = assert!(size_of::<{}>() == {size:#X});", c.ident).unwrap();
        stats.size_asserts += 1;
        stats.exact_classes += 1;
    } else {
        stats.partial_classes += 1;
    }
    for fo in &c.fields {
        writeln!(out, "{indent}const _: () = assert!(core::mem::offset_of!({}, {}) == {:#X});", c.ident, fo.ident, fo.f.off).unwrap();
        stats.offset_asserts += 1;
    }
    out.push('\n');
}

fn classes_rs(classes: &BTreeMap<&str, Class>, stats: &mut Stats) -> String {
    let mut out = String::from(HEADER);
    out.push_str("use core::ffi::c_void;\n\nuse super::vtables;\n\n");
    for c in classes.values().filter(|c| !c.partial()) {
        write_class(&mut out, c, false, classes, stats);
    }
    out.push_str("/// Classes whose size is only bounded below; each struct stops at the lower bound.\npub mod partial {\n");
    out.push_str("    use core::ffi::c_void;\n\n    use super::vtables;\n\n");
    for c in classes.values().filter(|c| c.partial()) {
        write_class(&mut out, c, true, classes, stats);
    }
    out.push_str("}\n");
    out
}

/// A semantic C signature as a Rust `unsafe extern "C" fn` type, or `None` when a type in it is
/// not one the generator can express (a class the ledgers have not laid out, a struct by value).
fn fn_type(signature: &str, classes: &BTreeMap<&str, Class>) -> Option<String> {
    let c_type = |t: &str| -> Option<String> {
        let t = t.trim();
        let (t, is_const) = t.strip_prefix("const ").map_or((t, false), |rest| (rest, true));
        let base = t.trim_end_matches('*').trim();
        let depth = t.len() - t.trim_end_matches('*').len();
        let inner = match base {
            "void" => (depth > 0).then(|| "c_void".to_owned())?,
            "char" => "c_char".to_owned(),
            "bool" => "bool".to_owned(),
            "uchar" => "u8".to_owned(),
            "ushort" => "u16".to_owned(),
            "uint" | "u32" => "u32".to_owned(),
            "int" | "i32" => "i32".to_owned(),
            "float" | "f32" => "f32".to_owned(),
            "double" | "f64" => "f64".to_owned(),
            "ulonglong" | "u64" => "u64".to_owned(),
            "longlong" | "i64" => "i64".to_owned(),
            "u8" | "u16" | "i8" | "i16" => base.to_owned(),
            other => (depth > 0).then(|| classes.get(other).map(Class::path))??,
        };
        let mut out = inner;
        for level in 0..depth {
            out = format!("{} {out}", if level == 0 && is_const { "*const" } else { "*mut" });
        }
        Some(out)
    };
    let (head, tail) = signature.split_once('(')?;
    let params = tail.strip_suffix(')')?;
    let ret_c = head.trim().rsplit_once(char::is_whitespace).map_or(head.trim(), |(ret, _)| ret);
    let ret = if ret_c.trim() == "void" { String::new() } else { format!(" -> {}", c_type(ret_c)?) };
    let mut args = Vec::new();
    if !matches!(params.trim(), "" | "void") {
        for p in params.split(',') {
            let (ty, name) = p.trim().rsplit_once(char::is_whitespace)?;
            args.push(format!("{}: {}", ident(name), c_type(ty)?));
        }
    }
    Some(format!("unsafe extern \"C\" fn({}){ret}", args.join(", ")))
}

fn symbol_doc(s: &Symbol) -> String {
    let mut d = format!("`{}` at {:#x} ({}, {})", s.name, s.rva, s.evidence, s.confidence);
    if !s.signature.is_empty() {
        let tier = if s.sig_confidence.is_empty() { "untiered" } else { &s.sig_confidence };
        write!(d, "; signature ({tier}): `{}`", s.signature).unwrap();
    }
    doc(&d)
}

fn vtables_rs(inp: &Inputs, classes: &BTreeMap<&str, Class>, stats: &mut Stats) -> String {
    let by_rva: HashMap<u64, &Symbol> = inp.symbols.iter().map(|s| (s.rva, s)).collect();
    let mut named: HashMap<(&str, u64), &SemSlot> = HashMap::new();
    for pass in &inp.semantic {
        for vt in &pass.vtables {
            for slot in &vt.slots {
                assert!(named.insert((vt.class.as_str(), slot.index), slot).is_none(), "{} slot {} named twice", vt.class, slot.index);
            }
        }
    }
    let mut out = String::from(HEADER);
    out.push_str("use core::ffi::{c_char, c_void};

use crate::Vtable;
use super::classes;

");
    let mut all = Vec::new();
    let mut rtti: Vec<_> = inp.rtti.classes.iter().collect();
    rtti.sort_by(|a, b| a.name.cmp(&b.name));
    for class in rtti {
        let class_ident = &classes[class.name.as_str()].ident;
        let mut cols: Vec<_> = class.cols.iter().collect();
        cols.sort_by_key(|c| c.offset);
        for col in cols {
            let sym = by_rva.get(&col.vtable).unwrap_or_else(|| panic!("{}: vtable at {:#x} has no symbol", class.name, col.vtable));
            let id = sym.id.unwrap_or_else(|| panic!("{}: vtable symbol {} has no id", class.name, sym.name));
            let vt = vtable_ident(class_ident, col.offset);
            let mut members = String::new();
            let mut aliases = String::new();
            writeln!(out, "/// `{}` at {:#x}, id {id} ({}, {}); {} slots.", doc(&sym.name), sym.rva, sym.evidence, sym.confidence, col.slots.len()).unwrap();
            writeln!(out, "#[repr(C)]
pub struct {vt} {{").unwrap();
            for (i, target) in col.slots.iter().enumerate() {
                let mut d = match by_rva.get(target) {
                    Some(t) => symbol_doc(t),
                    None => format!("no symbol at {target:#x}"),
                };
                let slot = if col.offset == 0 { named.get(&(class.name.as_str(), i as u64)) } else { None };
                if let Some(slot) = slot {
                    let name = ident(&slot.name);
                    write!(d, "; `{}`: {} ({}); semantic signature: `{}`", slot.name, doc(&slot.meaning), slot.confidence, doc(&slot.signature)).unwrap();
                    writeln!(members, "    pub const SLOT_{name}: usize = {i};").unwrap();
                    stats.named_slots += 1;
                    if slot.confidence == "high"
                        && let Some(ty) = fn_type(&slot.signature, classes)
                    {
                        let alias = format!("{vt}_{name}");
                        writeln!(members, "    /// Slot {i} as `{alias}`, `None` when the slot is null.
    #[must_use]
    pub fn {name}(&self) -> Option<{alias}> {{
        unsafe {{ core::mem::transmute::<*const c_void, Option<{alias}>>(self.slot_{i}) }}
    }}").unwrap();
                        writeln!(aliases, "/// `{}::{}`, slot {i}: {} ({}).
pub type {alias} = {ty};", class.name, slot.name, doc(&slot.meaning), slot.confidence).unwrap();
                        stats.typed_slots += 1;
                    }
                }
                writeln!(out, "    /// {d}").unwrap();
                writeln!(out, "    pub slot_{i}: *const c_void,").unwrap();
                stats.slots += 1;
            }
            writeln!(out, "}}
impl {vt} {{
    pub const ID: u64 = {id};
{members}}}").unwrap();
            if !aliases.is_empty() {
                out.push_str(&aliases);
            }
            out.push('\n');
            all.push((sym.rva, class.name.as_str(), col.offset, id));
            stats.vtables += 1;
        }
    }
    all.sort_unstable();
    out.push_str("/// Every vtable the RTTI records, sorted by rva.
pub static ALL: &[Vtable] = &[
");
    for (rva, class, offset, id) in all {
        writeln!(out, "    Vtable {{ class: {class:?}, offset: {offset:#X}, id: {id}, rva: {rva:#x} }},").unwrap();
    }
    out.push_str("];

/// The vtable at a module-relative address.
#[must_use]
pub fn find(rva: u32) -> Option<&'static Vtable> {
    ALL.binary_search_by_key(&rva, |v| v.rva).ok().map(|i| &ALL[i])
}
");
    out
}

fn is_funclet(s: &Symbol) -> bool {
    s.evidence == "eh_table" || s.name.contains("__unwind_") || s.name.contains("__catch_")
}

fn is_placeholder(name: &str) -> bool {
    name.strip_prefix("ID_").is_some_and(|rest| !rest.is_empty() && rest.bytes().all(|b| b.is_ascii_digit()))
}

/// `pub const <ident>: u64 = <id>` per symbol, with `docs` as the doc comment and `after` emitted below the const.
fn consts_rs(
    symbols: Vec<&Symbol>,
    header: &str,
    docs: &dyn Fn(&Symbol) -> String,
    after: &dyn Fn(&Symbol, &str) -> String,
    count: &mut usize,
) -> String {
    let mut symbols = symbols;
    symbols.sort_by(|a, b| a.name.cmp(&b.name).then(a.id.cmp(&b.id)));
    let mut idents: Vec<String> = symbols.iter().map(|s| ident(&s.name)).collect();
    unique(&mut idents);
    let mut out = String::from(HEADER);
    out.push_str(header);
    for (s, id) in symbols.iter().zip(idents) {
        writeln!(out, "/// {}\npub const {id}: u64 = {};", docs(s), s.id.unwrap()).unwrap();
        out.push_str(&after(s, &id));
        *count += 1;
    }
    out
}

fn fns_rs(inp: &Inputs, classes: &BTreeMap<&str, Class>, stats: &mut Stats) -> String {
    let mut semantic: HashMap<u64, &SemFunction> = HashMap::new();
    for pass in &inp.semantic {
        for f in pass.functions.iter().filter(|f| f.id.is_some()) {
            assert!(semantic.insert(f.id.unwrap(), f).is_none(), "{}: function id {} is in two semantic passes", f.name, f.id.unwrap());
        }
    }
    let selected: Vec<&Symbol> = inp
        .symbols
        .iter()
        .filter(|s| {
            s.kind == "function"
                && s.id.is_some()
                && matches!(s.confidence.as_str(), "high" | "medium")
                && !is_placeholder(&s.name)
                && !is_funclet(s)
        })
        .collect();
    let docs = |s: &Symbol| match semantic.get(&s.id.unwrap()) {
        Some(f) => format!("{}; {} ({}); semantic signature: `{}`", symbol_doc(s), doc(&f.meaning), f.confidence, doc(&f.signature)),
        None => symbol_doc(s),
    };
    let typed = std::cell::Cell::new(0);
    let after = |s: &Symbol, id: &str| {
        let Some(f) = semantic.get(&s.id.unwrap()).filter(|f| f.confidence == "high") else { return String::new() };
        let Some(ty) = fn_type(&f.signature, classes) else { return String::new() };
        typed.set(typed.get() + 1);
        format!("/// `{}` as a function pointer type ({}).\npub type {id}_fn = {ty};\n", f.name, f.confidence)
    };
    let out = consts_rs(selected, "use core::ffi::{c_char, c_void};\n\nuse super::classes;\n\n", &docs, &after, &mut stats.functions);
    stats.typed_functions = typed.get();
    out
}

fn globals_rs(inp: &Inputs, stats: &mut Stats) -> String {
    let labels: HashMap<u64, _> = inp.structs.labels.iter().filter(|l| l.pointer).map(|l| (l.rva, l)).collect();
    let mut semantic: HashMap<u64, &SemGlobal> = HashMap::new();
    for pass in &inp.semantic {
        for g in pass.globals.iter().filter(|g| g.id.is_some()) {
            assert!(semantic.insert(g.id.unwrap(), g).is_none(), "global id {} is in two semantic passes", g.id.unwrap());
        }
    }
    let selected = inp.symbols.iter().filter(|s| s.kind == "global" && s.id.is_some()).collect();
    let docs = |s: &Symbol| {
        let mut d = match labels.get(&s.rva) {
            Some(l) => format!("{}; pointer to `{}`: {}", symbol_doc(s), l.cls, doc(&l.detail)),
            None => symbol_doc(s),
        };
        if let Some(g) = semantic.get(&s.id.unwrap()) {
            write!(d, "; {} ({}); type `{}`", doc(&g.meaning), g.confidence, g.ty).unwrap();
            if let Some(a) = g.accessor_id {
                write!(d, "; accessor id {a}").unwrap();
            }
        }
        d
    };
    consts_rs(selected, "", &docs, &|_, _| String::new(), &mut stats.globals)
}

fn enums_rs(inp: &Inputs, stats: &mut Stats) -> String {
    let source = inp.symbols.iter().find(|s| s.name == "g_FormTypeSignatures");
    let mut out = String::from(HEADER);
    let mut forms: Vec<_> = inp.formtypes.iter().collect();
    forms.sort_by_key(|f| f.id);
    let mut idents: Vec<String> = forms.iter().map(|f| ident(&f.sig)).collect();
    unique(&mut idents);
    out.push_str("/// Record signatures indexed by form type");
    if let Some(s) = source {
        write!(out, ", from {}", symbol_doc(s)).unwrap();
    }
    out.push_str(".\n/// The `u8` width is the generator's choice for a table of this length; the ledger does not record the field width.\n");
    for pass in &inp.semantic {
        for e in pass.enums.iter().filter(|e| e.name == "FormType") {
            for v in &e.values {
                let f = forms.iter().find(|f| f.id == v.value).unwrap_or_else(|| panic!("FormType {} is not in formtypes.json", v.value));
                assert!(f.sig == v.name, "FormType {}: {} in the {} pass, {} in formtypes.json", v.value, v.name, pass.subsystem, f.sig);
            }
            writeln!(out, "/// {} ({} pass).", doc(&e.meaning), pass.subsystem).unwrap();
        }
    }
    out.push_str("#[repr(u8)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum FormType {\n");
    for (f, id) in forms.iter().zip(&idents) {
        match &f.cls {
            Some(c) => writeln!(out, "    /// `{}`, class `{c}`", f.sig).unwrap(),
            None => writeln!(out, "    /// `{}`", f.sig).unwrap(),
        }
        writeln!(out, "    {id} = {},", f.id).unwrap();
        stats.enum_values += 1;
    }
    out.push_str("}\n\nimpl FormType {\n    #[must_use]\n    pub const fn from_u8(value: u8) -> Option<Self> {\n        match value {\n");
    for (f, id) in forms.iter().zip(&idents) {
        writeln!(out, "            {} => Some(Self::{id}),", f.id).unwrap();
    }
    out.push_str("            _ => None,\n        }\n    }\n\n    #[must_use]\n    pub const fn signature(self) -> &'static str {\n        match self {\n");
    for (f, id) in forms.iter().zip(&idents) {
        writeln!(out, "            Self::{id} => {:?},", f.sig).unwrap();
    }
    out.push_str("        }\n    }\n}\n");

    for pass in &inp.semantic {
        for e in pass.enums.iter().filter(|e| e.name != "FormType") {
            let repr = match e.width {
                1 => "u8",
                2 => "u16",
                4 => "u32",
                8 => "u64",
                w => panic!("enum {}: width {w}", e.name),
            };
            let mut values: Vec<_> = e.values.iter().collect();
            values.sort_by_key(|v| v.value);
            let mut idents: Vec<String> = values.iter().map(|v| ident(&v.name)).collect();
            unique(&mut idents);
            writeln!(out, "\n/// {} ({} pass).\n#[repr({repr})]\n#[derive(Clone, Copy, PartialEq, Eq, Debug)]\npub enum {} {{", doc(&e.meaning), pass.subsystem, e.name).unwrap();
            for (v, id) in values.iter().zip(&idents) {
                writeln!(out, "    /// `{}`\n    {id} = {},", v.name, v.value).unwrap();
                stats.enum_values += 1;
            }
            writeln!(out, "}}\n\nimpl {} {{\n    #[must_use]\n    pub const fn from_{repr}(value: {repr}) -> Option<Self> {{\n        match value {{", e.name).unwrap();
            for (v, id) in values.iter().zip(&idents) {
                writeln!(out, "            {} => Some(Self::{id}),", v.value).unwrap();
            }
            out.push_str("            _ => None,\n        }\n    }\n}\n");
        }
    }

    let mut sets: Vec<_> = inp.semantic.iter().flat_map(|p| p.flags.iter().map(move |f| (f, p.subsystem.as_str()))).collect();
    sets.sort_by(|a, b| a.0.name.cmp(&b.0.name));
    for (set, pass) in sets {
        let (class, field) = set.name.split_once('.').unwrap_or_else(|| panic!("flag set {} is not Class.field", set.name));
        let repr = match set.width {
            8 => "u8",
            16 => "u16",
            32 => "u32",
            64 => "u64",
            w => panic!("flag set {}: width {w}", set.name),
        };
        let name = format!("{}_{}", ident(class), ident(field));
        writeln!(out, "\n/// Named bits of `{class}.{field}` ({pass} pass); unnamed bits pass through `bits`.\n#[repr(transparent)]\n#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]\npub struct {name}(pub {repr});\n\nimpl {name} {{").unwrap();
        for v in &set.values {
            writeln!(out, "    /// {} ({})\n    pub const {}: Self = Self({:#x});", doc(&v.meaning), v.confidence, screaming(&v.name), v.value).unwrap();
            stats.flags += 1;
        }
        writeln!(out, "\n    #[must_use]\n    pub const fn bits(self) -> {repr} {{\n        self.0\n    }}\n\n    #[must_use]\n    pub const fn contains(self, other: Self) -> bool {{\n        self.0 & other.0 == other.0\n    }}\n}}").unwrap();
    }
    out
}

fn mod_rs(inp: &Inputs, commit: &str) -> String {
    let passes: Vec<&str> = inp.semantic.iter().map(|p| p.subsystem.as_str()).collect();
    format!(
        "//! SkyrimSE.exe 1.7.104 as the SkyrimRE-1.7.104 ledgers describe it at commit {commit}.\n\
         //! Semantic passes folded in: {}.\n\
         //! Generated by `cargo xtask gen`; do not edit.\n\n\
         #[rustfmt::skip]\npub mod classes;\n#[rustfmt::skip]\npub mod enums;\n#[rustfmt::skip]\npub mod fns;\n\
         #[rustfmt::skip]\npub mod globals;\n#[rustfmt::skip]\npub mod vtables;\n\n\
         /// The runtime these definitions describe, as `[major, minor, build]`.\npub const VERSION: [u32; 3] = [1, 7, 104];\n",
        if passes.is_empty() { "none".to_owned() } else { passes.join(", ") }
    )
}

/// The generated module files keyed by file name, and what they contain.
pub fn all(inp: &Inputs, commit: &str) -> (BTreeMap<&'static str, String>, Stats) {
    let mut stats = Stats::default();
    let classes = build_classes(inp);
    let mut files = BTreeMap::new();
    files.insert("classes.rs", classes_rs(&classes, &mut stats));
    files.insert("vtables.rs", vtables_rs(inp, &classes, &mut stats));
    files.insert("fns.rs", fns_rs(inp, &classes, &mut stats));
    files.insert("globals.rs", globals_rs(inp, &mut stats));
    files.insert("enums.rs", enums_rs(inp, &mut stats));
    files.insert("mod.rs", mod_rs(inp, commit));
    (files, stats)
}
